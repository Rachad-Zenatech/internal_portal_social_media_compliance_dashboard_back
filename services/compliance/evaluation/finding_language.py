"""Shared writing instructions for creator and reviewer explanations; never change evidence or policy."""

PLAIN_LANGUAGE = """
Write explanations for a busy content creator, not a compliance specialist:
- Use plain English, short sentences and familiar words. Address the reader as "you" when giving an action.
- Explain what in this post caused the concern and why it matters under the supplied rule.
- For NEEDS_REVIEW or UNCLEAR, name exactly what is uncertain or missing. Do not present a possible issue as proven.
- If the source supports part of a claim, say which part it supports and which part still needs checking.
  Do not leave a review explanation that only says the source supports the claim without naming an unresolved gap.
- In reasoning/evidence, explain the concern. In recommended_action/note, give a specific next step:
  what to check, change, remove, label or provide. If the issue is uncertain, ask the reader to check it first.
- Say "the source does not clearly support this claim" rather than "does not settle the assertion";
  say "the text is too small or blurry to read confidently" rather than "an enlarged section suggests prohibited wording".
- Avoid generic instructions such as "ensure compliance", technical processing details and legal jargon.
  Keep essential technical facts, names, amounts, qualifications, negations and distinctions accurate.
- Keep copied evidence, claim text and source quotations exactly as written. Simplify only your explanations and actions.
These are writing instructions only: keep the supplied rule, decision criteria, confidence and evidence requirements.
"""
